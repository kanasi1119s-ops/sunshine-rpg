const NAMES: Record<string, string> = { arbiter: "悪神巨人兵", hero: "ユーリ", reto: "レト", mina: "ミナ", guide: "コハク", orca: "オルカ", ayame: "アヤメ" };

/** 会話の文（「名前「せりふ」」）。members は、いまパーティにいる人のID（hero をふくむ）。 */
export function arbiterIntro(truthKnown: boolean, members: readonly string[]): string[] {
  return (truthKnown ? AFTER : BEFORE)
    .filter(([who]) => who === "arbiter" || who === "hero" || members.includes(who))
    .map(([who, text]) => `${NAMES[who]}「${text}」`);
}
