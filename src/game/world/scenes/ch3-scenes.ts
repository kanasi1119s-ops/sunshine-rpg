import type { EventCommand } from "../../event/types";
import type { StoryScene } from "../story-scenes";

/** 地の文（話し手なし）か、セリフ（話し手つき）。 */
function say(text: string, speaker?: string): EventCommand {
  return speaker ? { type: "message", text, speaker } : { type: "message", text };
}

/** コハクが仲間のときだけ流す部分（第2章で同行を断った場合は、コハクの台詞を出さない）。 */
function withGuide(then: EventCommand[], otherwise?: EventCommand[]): EventCommand {
  return otherwise
    ? { type: "if", flag: "chapter2_guide_joined", equals: true, then, else: otherwise }
    : { type: "if", flag: "chapter2_guide_joined", equals: true, then };
}

