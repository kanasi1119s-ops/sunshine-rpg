/** 話し手つきの文（話し手を省くと地の文）。 */
const m = (text: string, speaker?: string): EventCommand => (speaker ? { type: "message", text, speaker } : { type: "message", text });
const cine: EventCommand = { type: "cinematic", on: true };
const dark = (on: boolean): EventCommand => ({ type: "screen", dark: on });
const time = (t: "morning" | "day" | "dusk" | "night"): EventCommand => ({ type: "time", time: t });

/** 終章の場面（ch9-scenes.ts）の中身をそのまま使い、別々に流れないよう「見た」しるしを立てる。 */
const ch9 = (id: string): EventCommand[] => {
  const scene = CH9_SCENES.find((s) => s.id === id);
  if (!scene) throw new Error(`終章の場面がない: ${id}`);
  return [{ type: "setFlag", flag: sceneSeenFlag(id), value: true }, ...scene.commands];
};

