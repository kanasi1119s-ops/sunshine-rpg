import { overrides } from "./sprite.mjs";
import { rows as yuri } from "./yuri-front.mjs";
// オルカ（鉄鏈鉱山出身、元鉱山労働者。寡黙で頑固）。ユーリの骨組みをもとに、短く刈った白髪まじりの髪・無精ひげ・眉の傷・橙の首巻き・広い肩と革のベストにした（別のキャラクター）。
export const pal = { p: "#2a2a30", "1": "#4a4a52", "2": "#7a7a84", "3": "#aaaab4", "4": "#dcdce4", J: "#4a3020", j: "#7a5030", k: "#a87840", K: "#d8a868", r: "#221408", C: "#e8dcc0", S: "#d86a20", W: "#f4a860", P: "#3a3a44", Q: "#5a5a68", a: "#a86a52", b: "#d09070", c: "#e8b090", d: "#f4d0b0", q: "#5a3428", n: "#6a3a30", B: "#5a3a20" };
const L = [];
// 短く刈った髪: 額の生え際を上げ、側頭部を短く（横髪を消す）
for (let y = 10; y <= 13; y++) for (const x of [6, 7, 24, 25]) L.push([x, y, "1"]);
for (let y = 14; y <= 18; y++) for (const x of [6, 7, 24, 25]) L.push([x, y, y > 15 ? "a" : "1"]);
// 眉を太く・眉から頬への傷（向かって左）
for (const x of [9, 10, 11, 20, 21, 22]) L.push([x, 13, "p"]);
for (const [x, y] of [[9, 12], [10, 13], [10, 14], [11, 15], [11, 16], [12, 17]]) L.push([x, y, "q"]);
// 目: 鋭い細い目
for (const x0 of [9, 20]) { L.push([x0, 14, "e"], [x0 + 1, 14, "e"], [x0 + 2, 14, "e"], [x0, 15, "w"], [x0 + 1, 15, "e"], [x0 + 2, 15, "i"], [x0, 16, "c"], [x0 + 1, 16, "c"], [x0 + 2, 16, "c"]); }
// 無精ひげ（あご・口のまわり）
for (let y = 18; y <= 21; y++) for (let x = 10; x <= 21; x++) if ((x + y) % 2 === 0 && !(y === 18 && x > 13 && x < 18)) L.push([x, y, "q"]);
L.push([14, 18, "n"], [15, 18, "n"], [16, 18, "n"], [17, 18, "n"]);
// 橙の首巻き
for (let x = 11; x <= 20; x++) L.push([x, 22, "S"]); for (let x = 12; x <= 19; x++) L.push([x, 23, "S"]); L.push([12, 22, "W"], [13, 22, "W"], [15, 23, "W"]);
// 広い肩・腕（幅をひろげる）
for (let y = 22; y <= 27; y++) for (const x of [4, 5, 26, 27]) L.push([x, y, x <= 5 ? (x === 4 ? "r" : "J") : x === 26 ? "j" : "r"]);
// 腕輪なし・手は大きく
L.push([24, 27, "b"], [25, 27, "b"], [4, 27, "b"], [5, 27, "b"], [4, 28, "b"], [5, 28, "a"], [26, 28, "b"], [27, 28, "a"]);
export const rows = overrides(yuri, L);
