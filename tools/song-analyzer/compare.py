#!/usr/bin/env python3
"""カルテの差分: お手本の曲と自分の曲のカルテを並べて、違いを出す（学習用）。
使い方: python3 tools/song-analyzer/compare.py <お手本.karte.json> <自分.karte.json>"""
import sys, json, numpy as np
JP = {"vocals": "歌", "drums": "ドラム", "bass": "ベース", "chordal": "和音の楽器"}
def feats(k):
    pb = k["per_bar"]; nb = k["bars"]; act = pb["active"]; f = {}
    f["伴奏が休んでいる時間（%）"] = k["rests"]["伴奏が休んでいる時間の割合"] * 100; f["全員が休んでいる時間（%）"] = k["rests"]["全員が休んでいる時間の割合"] * 100
    if k["rests"]["歌が休んでいる時間の割合"] is not None: f["歌が休んでいる時間（%）"] = k["rests"]["歌が休んでいる時間の割合"] * 100
    f["小節ごとの音量の幅（dB）"] = k["loudness"]["range_db"]; f["重なる楽器の数（平均）"] = k["layers"]["mean"]; f["重なる楽器の数が変わる回数（8小節あたり）"] = k["layers"]["changes_per_8bars"]
    f["重なる楽器が2つ以下の小節（%）"] = float(np.mean(np.array(pb["layers"]) <= 2) * 100)
    for c in JP:
        if k["stems_present"].get(c): f[f"{JP[c]}が休んでいる小節（%）"] = float(np.mean(np.array(act[c]) < 0.3) * 100)
    f["1場面の長さ（秒・中央値）"] = float(np.median([s.get("length_sec", s["bars"] * 240 / k["tempo"]) for s in k["sections"]])); f["場面の数（1分あたり）"] = len(k["sections"]) / k["seconds"] * 60
    ld = [s["loud_db"] for s in k["sections"]]; ld = [x for x in ld if x > max(ld) - 20]      # 無音に近い場面（曲の頭・終わりの余白）は除く
    f["場面ごとの音量の差（いちばん大きい − いちばん小さい・dB）"] = max(ld) - min(ld)
    spb_ = 60 / k["tempo"]
    for d, v in k["drums_hits_per_beat"].items(): f[f"ドラム: {d}（1秒あたり）"] = v / spb_
    s2 = k.get("stage2") or {}
    def put(name, v, mul=1):
        if v is not None: f[name] = float(v) * mul
    d = s2.get("ドラム")
    if d:
        r = d.get("キックとスネアの型のくり返し（8分にまとめて）") or {}
        put("ドラム: 前か2小節前との似かた（キックとスネア・0〜100）", d.get("前か2小節前との似かた（キックとスネア・8分にまとめて）"), 100); put("ドラム: 前か2小節前との似かた（刻み・0〜100）", d.get("前か2小節前との似かた（刻み・8分にまとめて）"), 100)
        put("ドラム: 前か2小節前と同じ型の小節（8分にまとめて・%）", r.get("前か2小節前と同じ型の割合（くり返しの多さ）"), 100); put("ドラム: 8小節の中の型の種類（8分にまとめて）", r.get("8小節の中の型の種類（平均）"))
        put("ドラム: フィルらしい小節（8小節あたり）", d.get("フィルらしい小節の数（8小節あたり）")); put("ドラム: スネアの弱い打の割合（%）", d.get("スネアの弱い打（ゴースト）の割合"), 100)
    b = s2.get("ベース")
    if b:
        r = b.get("型のくり返し") or {}
        put("ベース: 前か2小節前と同じ型の小節（%）", r.get("前か2小節前と同じ型の割合（くり返しの多さ）"), 100); put("ベース: 8小節の中の型の種類", r.get("8小節の中の型の種類（平均）")); put("ベース: 前か2小節前との似かた（0〜100）", b.get("前か2小節前との似かた（音を出す場所・8分にまとめて）"), 100); put("ベース: 1小節の音の数", b.get("1小節の音の数（中央値）"))
        put("ベース: 根音を弾いている割合（%）", (b.get("和音の根音との関係") or {}).get("根音", 0), 100); m = b.get("動き方") or {}
        put("ベース: となりの音へ動く割合（%）", m.get("となりの音へ（1〜2半音）"), 100); put("ベース: 4度・5度で跳ぶ割合（%）", m.get("5度・4度（5〜7半音）"), 100); put("ベース: オクターブで跳ぶ割合（%）", m.get("オクターブ（12半音）"), 100); put("ベース: 音域（半音）", b.get("音域（半音）"))
    c = s2.get("和音")
    if c:
        put("和音: 変わる回数（1小節あたり）", c.get("和音が変わる回数（1小節あたり）")); put("和音: 小節の途中で変わる小節（%）", c.get("小節の途中で変わる小節の割合"), 100); q = c.get("和音の種類の割合") or {}
        put("和音: 根音が変わる回数（1小節あたり）", c.get("根音が変わる回数（1小節あたり）")); put("和音: 使っている根音の数", c.get("使っている根音の数（全体の3%以上）")); mv = c.get("根音の動き方の割合")
        if mv is not None:
            put("和音: 根音が4度・5度で動く割合（%）", mv.get("4度上（5度下）へ", 0) + mv.get("5度上（4度下）へ", 0), 100); put("和音: 根音がとなり（半音・2度）へ動く割合（%）", sum(mv.get(x, 0) for x in ("2度上へ", "2度下へ", "半音上へ", "半音下へ")), 100); put("和音: 根音が3度で動く割合（%）", sum(mv.get(x, 0) for x in ("短3度上へ", "短3度下へ", "長3度上へ", "長3度下へ")), 100)
        put("和音: 3和音でない和音の割合（%）", 1 - q.get("長3和音", 0) - q.get("短3和音", 0) - q.get("5度だけ（パワーコード）", 0), 100); put("和音: 短3和音の割合（%）", q.get("短3和音", 0), 100)
    v = s2.get("歌の旋律の形")
    if v and "音の長さの中央値（拍）" in v:
        spb_ = 60 / k["tempo"]; put("歌: 音の長さ（秒・中央値）", v.get("音の長さの中央値（拍）"), spb_); put("歌: 句の長さ（秒・中央値）", v.get("句の長さ（拍・中央値）"), spb_); put("歌: 句の最後が2拍以上（%）", v.get("句の最後が2拍以上の割合"), 100)
        put("歌: 長い音がウラから入る割合（%）", v.get("長い音が拍のウラ（食って入る）で始まる割合"), 100); put("歌: 音域（半音）", v.get("音域（半音）")); put("歌: 次の音とつながっている割合（%）", v.get("次の音とつながっている（すき間が16分の半分より短い）割合"), 100)
        put("歌: 跳ぶ動き（5半音以上）の割合（%）", v.get("跳ぶ動き（5半音以上）の割合"), 100); put("歌: 前か2小節前との似かた（0〜100）", v.get("前か2小節前との似かた（音を出す場所・8分にまとめて）"), 100); put("歌: 16分以下の短い音の割合（%）", v.get("16分以下の音の数の割合"), 100); put("歌: 2拍以上の長い音の割合（%）", v.get("2拍以上の音の数の割合"), 100); r = v.get("歌のリズムの型のくり返し") or {}
        put("歌: 前か2小節前と同じリズムの小節（%）", r.get("前か2小節前と同じ型の割合（くり返しの多さ）"), 100); put("歌: 8小節の中のリズムの種類", r.get("8小節の中の型の種類（平均）")); put("歌: 山の形の句の割合（%）", (v.get("句の形の割合") or {}).get("山（まん中が高い）", 0), 100)
    s3 = k.get("stage3") or {}
    for nm_, key in (("ベース", "ベース"), ("和音の楽器", "和音の楽器"), ("歌", "歌"), ("ドラム", "ドラム")):
        t = s3.get(key)
        if not t: continue
        put(f"音色・{nm_}: 音の重心（Hz）", t.get("音の重心（Hz）")); put(f"音色・{nm_}: 左右の広がり（中）", t.get("左右の広がり（中 250Hz〜2kHz）")); put(f"音色・{nm_}: 大きさのゆれ幅（dB）", t.get("大きさのゆれ幅（dB・鳴っている所）"))
        put(f"音色・{nm_}: 打つ音の成分の割合（%）", t.get("打つ音の成分の割合"), 100); bd = t.get("帯ごとの大きさ（dB・全体を0として）") or {}
        if nm_ in ("歌", "和音の楽器"): put(f"音色・{nm_}: 高い所（4〜8kHz）の大きさ（dB）", bd.get("高い（4〜8kHz）")); put(f"音色・{nm_}: とても高い所（8kHz〜）の大きさ（dB）", bd.get("とても高い（8kHz〜）"))
        if nm_ == "ベース": put("音色・ベース: 中の上（1〜2kHz）の大きさ（dB）", bd.get("中の上（1〜2kHz）")); put("音色・ベース: とても低い所（〜60Hz）の大きさ（dB）", bd.get("とても低い（〜60Hz）"))
        hm = t.get("倍音の形")
        if hm: put(f"音色・{nm_}: 倍音の下がり方（dB／オクターブ）", hm.get("倍音の下がり方（dB／オクターブ）"))
        ev = t.get("立ち上がりと余韻")
        if ev: put(f"音色・{nm_}: 立ち上がり（ミリ秒）", ev.get("立ち上がり（ミリ秒・10%→90%。20より短くは測れない）")); put(f"音色・{nm_}: 頭から0.2秒あとの大きさ（dB）", ev.get("頭から0.2秒あとの大きさ（dB・頭を0として）"))
        pm = t.get("拍に合わせたへこみ")
        if pm: put(f"音色・{nm_}: 拍に合わせたへこみの深さ（dB）", pm.get("へこみの深さ（dB）"))
        vb = t.get("ビブラート")
        if vb: put("音色・歌: ビブラートがある割合（%）", vb.get("そのうちビブラートがある割合"), 100); put("音色・歌: ビブラートの深さ（セント）", vb.get("ビブラートの深さ（セント・片側）")); put("音色・歌: ビブラートの速さ（Hz）", vb.get("ビブラートの速さ（Hz）"))
    ds = s3.get("ドラムの音") or {}
    if "キック" in ds: put("音色・キック: 高さ（Hz）", ds["キック"].get("いちばん強い高さ（Hz）")); put("音色・キック: 長さ（ミリ秒）", ds["キック"].get("長さ（ミリ秒・−20dB まで）")); put("音色・キック: カチッの強さ（dB）", ds["キック"].get("「カチッ」の強さ（2〜6kHz の割合・dB）"))
    if "スネア" in ds: put("音色・スネア: 胴の高さ（Hz）", ds["スネア"].get("胴の高さ（Hz）")); put("音色・スネア: 余韻（ミリ秒）", ds["スネア"].get("余韻（ミリ秒・−20dB まで）")); put("音色・スネア: 明るさ（dB）", ds["スネア"].get("明るさ（4kHz より上の割合・dB）"))
    if "ハイハット" in ds: put("音色・ハイハット: 音の重心（Hz）", ds["ハイハット"].get("音の重心（Hz・3kHz より上）")); put("音色・ハイハット: 長さ（ミリ秒）", ds["ハイハット"].get("長さ（ミリ秒・−20dB まで）"))
    f["低い音の割合（%）"] = k["loudness"]["low"] * 100; f["高い音の割合（%）"] = k["loudness"]["high"] * 100; f["左右の広がり"] = k["loudness"]["width"]
    return f
if __name__ == "__main__":
    a, b = (json.load(open(p)) for p in sys.argv[1:3])
    fa, fb = feats(a), feats(b); rows = []
    SCALE = {"（%）": 10, "（dB）": 3, "": 1}
    for key in fa:
        if key not in fb: continue
        x, y = fa[key], fb[key]; sc = 10 if "%" in key else (3 if "dB" in key else max(0.3, abs(x) * 0.3)); rows.append((abs(x - y) / sc, key, x, y))
    print(f"お手本: {a['name']}（テンポ {a['tempo']}・{a['seconds']}秒）   自分: {b['name']}（テンポ {b['tempo']}・{b['seconds']}秒）\n違いが大きい順:")
    for d, key, x, y in sorted(rows, reverse=True):
        print(f"  {'★' if d >= 1 else '・'} {key}: お手本 {x:.1f} ／ 自分 {y:.1f}")
