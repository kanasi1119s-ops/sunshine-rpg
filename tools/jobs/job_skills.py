def spec(mp, kind, *a, hp=None):
    if kind == "s": d = f'{{ mpCost: {mp}, powerMultiplier: {a[0]}'
    elif kind == "m": d = f'{{ mpCost: {mp}, powerMultiplier: {a[1]}, effect: "multi", hits: {a[0]}'
    elif kind == "a": d = f'{{ mpCost: {mp}, powerMultiplier: {a[0]}, effect: "damageAll"'
    elif kind == "p": d = f'{{ mpCost: {mp}, powerMultiplier: {a[0]}, effect: "pierceAll"'
    elif kind == "h": d = f'{{ mpCost: {mp}, powerMultiplier: 0, effect: "heal", healRatio: {a[0]}'
    elif kind == "H": d = f'{{ mpCost: {mp}, powerMultiplier: 0, effect: "healAll", healRatio: {a[0]}'
    elif kind in ("b", "B"):
        t = a[2] if len(a) > 2 else 3
        d = f'{{ mpCost: {mp}, powerMultiplier: 0, effect: "{"buff" if kind == "b" else "buffAll"}", stat: "{ST[a[0]]}", mult: {a[1]}, turns: {t}'
    elif kind in ("d", "D"):
        ch = a[2] if len(a) > 2 else 0.85
        d = f'{{ mpCost: {mp}, powerMultiplier: 0, effect: "{"debuff" if kind == "d" else "debuffAll"}", stat: "{ST[a[0]]}", mult: {a[1]}, turns: 3, chance: {ch}'
    elif kind in ("sl", "po", "cf"):
        eff = {"sl": "sleep", "po": "poison", "cf": "confuse"}[kind]
        d = f'{{ mpCost: {mp}, powerMultiplier: 0, effect: "{eff}", chance: {a[0]}, turns: {a[1]}'
    elif kind == "r": d = f'{{ mpCost: {mp}, powerMultiplier: 0, effect: "restoreHalf"'
    elif kind == "k": d = f'{{ mpCost: {mp}, powerMultiplier: {a[1]}, koChance: {a[0]}'
    else: raise ValueError(kind)
    if hp: d += f", hpCost: {hp}"
    return d + " }"

