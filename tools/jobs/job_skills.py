def ts_skill(row, star):
    name, desc, mp, kind, *a = row
    hp = None
    if a and isinstance(a[-1], tuple):
        hp = a[-1][1]; a = a[:-1]
    return f'      {{ name: "{name}", requiredStars: {star}, description: "{desc}", battle: {spec(mp, kind, *a, hp=hp)} }},'

src = open(P, encoding="utf-8").read()
