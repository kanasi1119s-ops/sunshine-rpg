for jid, rows in J.items():
    assert len(rows) == 15, jid
    stars = DIVINE_STARS if jid in DIVINE else list(range(1, 16))
    body = "\n".join(ts_skill(r, s) for r, s in zip(rows, stars))
    names += [r[0] for r in rows]
    i = src.index(f'id: "{jid}"')
    a = src.index("skills: [", i) + len("skills: [")
    b = src.index("\n    ],", a)
    src = src[:a] + "\n" + body + src[b:]
dup = {n for n in names if names.count(n) > 1}
assert not dup, dup
open(P, "w", encoding="utf-8").write(src)
