"""帆走船（32×32、船底の下端＝枠の下から6ドット上＝y=25）と停泊中の船（48×48）。
灯の環の意匠（青い輪）を帆に入れる。"""
from lib import Canvas


def ring_emblem(c, cx, cy, r=2.6, col="L"):
    """帆に入れる小さな輪（灯の環）。中心 (cx,cy)。"""
    c.ring(cx, cy, r, r, 0.45, col, only="Pp")


def wake_side(c, x0, x1, y):
    """横向きの船の航跡（白い波）。船底の下に帯、うしろに尾を引く。"""
    for x in range(x0, x1):
        k = (x - x0)
        c.px(x, y, "C" if k % 4 != 3 else "c")
        c.px(x, y + 1, "c" if k % 4 in (1, 2) else ".")


def ship_right():
    c = Canvas(32, 32)
    # --- 航跡（うしろ＝左へ長く）
    for x in range(1, 28):
        c.px(x, 26, "C" if x % 5 != 4 else "c")
    for x in range(0, 20):
        if x % 3 != 2:
            c.px(x, 27, "c")
    for x in range(0, 11):
        if x % 4 in (0, 1):
            c.px(x, 29, "C")
    c.px(2, 28, "C"); c.px(3, 28, "C"); c.px(7, 28, "C"); c.px(8, 28, "c")
    # 船首の波しぶき
    c.px(28, 25, "C"); c.px(29, 26, "C"); c.px(30, 25, "c"); c.px(27, 27, "c")
    # --- 船体（船尾が高く、船首がそる）
    hull = [(3, 17), (10, 17), (10, 20), (25, 20), (26, 19), (30, 18), (29, 22), (25, 25), (7, 25), (3, 22)]
    c.poly(hull, "M")
    c.poly([(5, 23.2), (26, 23.2), (24, 25), (7, 25)], "m", only="M")   # 船底（影）
    c.rect(3, 17, 10, 17, "N"); c.rect(10, 20, 25, 20, "N")             # 手すり・甲板
    c.rect(4, 19, 4, 22, "m")
    for x in range(12, 25, 4):                                          # 舷窓（砲門）
        c.px(x, 22, "K")
    c.line(25, 19, 30, 18, "N")
    # --- マスト
    c.rect(14, 5, 14, 20, "m")
    c.rect(26, 11, 26, 19, "m")
    c.line(27, 19, 31, 16, "m")                                         # 船首の斜めの棒
    # 大きな帆（風をはらんで前にふくらむ）
    c.poly([(15, 6), (22, 7), (24, 11), (24, 14), (22, 18), (15, 18)], "P")
    c.poly([(21, 7), (22, 7), (24, 11), (24, 14), (22, 18), (20, 18), (20.5, 12)], "p", only="P")
    c.rect(15, 18, 22, 18, "p")
    ring_emblem(c, 18.5, 12, 3.0)
    # 前の小さな帆
    c.poly([(27, 12), (27, 18), (31, 16.3)], "P")
    c.poly([(27, 16), (27, 18), (31, 16.3)], "p", only="P")
    # 旗
    c.poly([(15, 3), (19, 4), (15, 5)], "R")
    c.px(14, 4, "m")
    return c.outline()


def ship_left():
    return ship_right().mirror()


def ship_down():
    """船首をこちらに向けて進んでくる姿（上から斜めに見る）。"""
    c = Canvas(32, 32)
    # 船首の波（左右にひろがる白い波）
    for i in range(0, 10):
        c.px(15 - i, 27 + (i // 3), "C" if i % 3 != 2 else "c")
        c.px(16 + i, 27 + (i // 3), "C" if i % 3 != 2 else "c")
    c.px(14, 26, "C"); c.px(17, 26, "C"); c.px(15, 28, "c"); c.px(16, 28, "c")
    for x in (6, 8, 10, 22, 24, 26):
        c.px(x, 30, "c")
    # 船体（上が船尾でやや広い、下が船首）
    c.poly([(8, 16), (24, 16), (24, 21), (21, 25), (16, 26), (11, 25), (8, 21)], "M")
    shade_x = lambda x, y: x >= 20 or y >= 24
    for y in range(16, 27):
        for x in range(8, 25):
            if c.get(x, y) == "M" and shade_x(x, y):
                c.px(x, y, "m")
    c.rect(9, 17, 23, 18, "N")                                          # 甲板
    c.rect(20, 17, 23, 18, "n")
    c.line(16, 20, 16, 25, "m")                                         # 竜骨のすじ
    for (x0, x1, y) in ((10, 15, 21), (17, 22, 21), (11, 15, 23), (17, 21, 23)):
        c.rect(x0, y, x1, y, "n" if x0 < 16 else "K")
    c.px(16, 24, "Y")                                                   # 船首のあかり
    # マスト・帆（正面）
    c.rect(16, 4, 16, 19, "m")
    c.poly([(7, 6), (25, 6), (25, 13), (23, 15), (9, 15), (7, 13)], "P")
    c.poly([(17, 6), (25, 6), (25, 13), (23, 15), (17, 15)], "p", only="P")
    c.rect(7, 15, 25, 15, "p"); c.rect(9, 15, 23, 15, "p")
    ring_emblem(c, 14.5, 10.5, 3.4)
    c.rect(7, 5, 25, 5, "m")                                            # 帆桁
    c.poly([(17, 1), (21, 2), (17, 3)], "R"); c.px(16, 2, "m"); c.rect(16, 3, 16, 3, "m")
    return c.outline()


def ship_up():
    """遠ざかっていく姿（船尾をこちらに向ける）。帆は裏側、船尾の窓。"""
    c = Canvas(32, 32)
    # 航跡（手前に向かってひろがるV字）
    for i in range(0, 9):
        c.px(13 - i, 27 + (i // 2), "C" if i % 2 == 0 else "c")
        c.px(18 + i, 27 + (i // 2), "C" if i % 2 == 0 else "c")
    for y in range(26, 32):
        if y % 2 == 0:
            c.px(15, y, "C"); c.px(16, y, "c")
    c.px(12, 26, "C"); c.px(19, 26, "C")
    # 船体（手前が船尾で広い、奥が船首）
    c.poly([(12, 16), (20, 16), (24, 19), (25, 24), (22, 26), (10, 26), (7, 24), (8, 19)], "M")
    c.poly([(7, 24), (25, 24), (22, 26), (10, 26)], "m", only="M")
    c.rect(9, 19, 23, 19, "N")
    c.rect(10, 20, 22, 23, "n")                                         # 船尾楼の壁
    c.rect(10, 20, 15, 23, "N")
    for x in (11, 14, 17, 20):
        c.rect(x, 21, x + 1, 22, "Y")
    c.rect(10, 20, 22, 20, "M")
    c.rect(8, 19, 24, 19, "N")
    # マスト・帆（裏から見るので、すこし暗い）
    c.rect(16, 4, 16, 17, "m")
    c.poly([(8, 5), (24, 5), (24, 12), (22, 14), (10, 14), (8, 12)], "p")
    c.poly([(8, 5), (16, 5), (16, 14), (10, 14), (8, 12)], "P", only="p")
    c.rect(10, 14, 22, 14, "p")
    ring_emblem(c, 15.5, 9.5, 3.2, "l")
    c.rect(7, 4, 25, 4, "m")
    c.poly([(17, 1), (21, 2), (17, 3)], "R"); c.px(16, 1, "m"); c.px(16, 2, "m"); c.px(16, 3, "m")
    return c.outline()


