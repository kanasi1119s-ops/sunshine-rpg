def diag_blade(c, bx, by, n, lit='S', shade='s'):
    """左下(bx,by)から右上へ n マスの刃。左上側が明るく、右下側が影。"""
    c.line(bx + 1, by, bx + n, by - n + 1, shade)
    c.line(bx, by, bx + n, by - n, lit)


def guard(c, cx, cy, half, lit='G', shade='H'):
    """刃に直角（左上-右下）のつば"""
    for i in range(-half, half + 1):
        c.px(cx + i, cy + i, lit if i <= 0 else shade)
    for i in range(-half + 1, half + 1):
        c.px(cx + i, cy + i - 1 + 1, lit if i <= 0 else shade)


def grip(c, x, y, n, a='W', b='w'):
    c.line(x, y, x - n, y + n, a)
    c.line(x + 1, y, x - n + 1, y + n, b)


