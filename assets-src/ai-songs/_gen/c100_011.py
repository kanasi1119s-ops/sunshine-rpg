# ケルト・フルート100曲「銀の笛と百の夜」011 草を渡る風 Wind Through the Grass（2026-10-28）。表は docs/sound/celtic-flute-100-plan.md
# 物語: 一面の草原を、風が通り抜けていく。草がなびくたびに、笛の息も強くなったり弱くなったりする。始め：風／終わり：風。山なし。
# 型: 風の強弱に合わせて揺れる旋律。笛の強さ（と竪琴の分散和音）を、8小節＝32秒の周期でゆらし、環境音の風のうねりも同じ周期にそろえる。
#     笛は001と同じく一音ずつなめらかに。重ね方は「音の重ね方の勉強ノート」どおり（テンションの和音・和声の笛・内声の動き）。
import sys, math
from c100_common import *

S = Song("C100", "011-wind-through-the-grass", "草を渡る風", "Wind Through the Grass", 60, 4, "D", "dorian", "ケルト（幻想）")
S.kit = "naked"; S.keep_old_synth = True
S.scene("風", 4, "intro", ["Dm", "Dm", "C", "Dm"])
S.scene("草原1", 16, "verse", ["Dm", "G", "Dm", "C", "F", "G", "Am", "Dm", "Dm", "C", "G", "Am", "F", "G", "Dm", "Dm"])
S.scene("草原2", 16, "verse", ["F", "C", "G", "Dm", "Am", "G", "F", "G", "Dm", "Em", "F", "G", "C", "G", "Dm", "Dm"])
S.scene("草原3", 16, "chorus", ["Dm", "G", "Am", "Em", "F", "C", "G", "Am", "F", "G", "Em", "Am", "G", "C", "Dm", "Dm"])
S.scene("風に還る", 8, "outro", ["Dm", "C", "Dm", "Dm", "Dm", "Dm", "Dm", "Dm"])
NAMES = ["風", "草原1", "草原2", "草原3", "風に還る"]

c = make(S, NAMES,
         [("風", 0, 0.62), ("草原1", 0, 0.64), ("草原2", 0, 0.68), ("草原3", 0, 0.72), ("草原3", 15, 0.68), ("風に還る", 0, 0.55), ("風に還る", 7, 0.3)],
         {"草原1": 0.64, "草原2": 0.64, "草原3": 0.66, "風に還る": 0.6},
         flute_gain={"草原1": 1.3, "草原2": 1.3, "草原3": 1.25, "風に還る": 1.15}, intro="風", passing=True, tension=True)
# 風のうねり（8小節で1周）：笛と竪琴の強さを 0.84〜1.0 でゆらす
WIND = [0.92 + 0.08 * math.sin(2 * math.pi * (b - 2) / 8) for b in range(c.NB)]
for tr in (c.FLUTE, c.HARP):
    tr.spec["barGain"] = [round(x * WIND[b], 3) for b, x in enumerate(tr.spec["barGain"])]

# ---------- 旋律（D ドリア。風にゆれる旋律） ----------
put_melody(c, "草原1", [
    ["R:1 1:1 2:1 3:1", "4:1 3:1 2:1 4:1", "5:1 4:1 3:1 2:1", "2:3 R:1"],
    ["3:1 4:1 5:1 3:1", "4:1 5:1 6:1 4:1", "5:1 3:1 1:1 3:1", "1:3 R:1"],
    ["5:1 4:1 3:1 4:1", "4:1 3:1 2:1 3:1", "4:1 6:1 5:1 4:1", "5:3 R:1"],
    ["5:1 4:1 3:1 5:1", "4:1 5:1 6:1 5:1", "3:1 2:1 1:1 2:1", "1:3 R:1"]], 5)
put_melody(c, "草原2", [
    ["3:1 5:1 7:1 5:1", "4:1 2:1 7,:1 2:1", "4:1 6:1 5:1 4:1", "3:3 R:1"],
    ["5:1 3:1 1:1 3:1", "4:1 6:1 7:1 6:1", "5:1 7:1 5:1 3:1", "4:3 R:1"],
    ["5:1 4:1 3:1 5:1", "6:1 5:1 4:1 2:1", "3:1 5:1 7:1 5:1", "6:3 R:1"],
    ["7:1 6:1 5:1 4:1", "6:1 5:1 4:1 6:1", "5:1 4:1 3:1 2:1", "1:3 R:1"]], 5)
put_melody(c, "草原3", [
    ["1:1 3:1 5:1 7:1", "6:1 5:1 4:1 6:1", "5:1 7:1 5:1 3:1", "2:3 R:1"],
    ["3:1 5:1 7:1 5:1", "4:1 2:1 7,:1 2:1", "4:1 6:1 7:1 6:1", "5:3 R:1"],
    ["5:1 7:1 6:1 5:1", "4:1 6:1 5:1 4:1", "2:1 4:1 6:1 4:1", "5:3 R:1"],
    ["4:1 6:1 5:1 4:1", "2:1 4:1 7,:1 2:1", "3:1 2:1 1:1 2:1", "1:3 R:1"]], 5)
put_bars(c, "風に還る", ["3:1 2:1 1:2", "R:4", "5,:1 6,:1 1:2", "R:4", "1:4", "R:4", "R:4", "R:4"], 5)

# ---------- 伴奏（竪琴の分散和音が草のなびき） ----------
for b in range(c.NB):
    n, i, L, k = S.scene_of(b); ch = S.chords[b]
    lo = low(ch, "C2"); t = tones(ch, "D3", "D6")
    v = voice(ch, 57, 3, spread=True)
    for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
    if n == "風":
        if i >= 1: c.HARP.bar(b, " ".join(f"{nm(t[q % len(t)])}:1" for q in (0, 2, 4, 2)))
    elif n.startswith("草原"):
        c.HARP.bar(b, " ".join(f"{nm(t[q % len(t)])}:0.5" for q in ((0, 2, 4, 5, 4, 2, 3, 2) if i % 2 == 0 else (1, 3, 5, 3, 4, 2, 3, 1))))
        if i % 4 == 3: c.HARP2.bar(b, f"R:2 {nm(t[-2])}:2")
        c.LOW.bar(b, f"{nm(lo + 12 if lo < 40 else lo)}:4")
    elif n == "風に還る":
        if i in (0, 2, 4): c.HARP.bar(b, " ".join(f"{nm(t[q % len(t)])}:1" for q in (0, 2, 4, 6)))

rich(c, choir_scenes=["草原2", "草原3"], pulse_scenes=["草原2", "草原3"], guitar=False)

finish(c, "--sound celtic-fantasy --orchestra vsco --piano salamander --space dome --space-wet 0.3 --master -15 --widen 1.0",
       "ケルト・フルート100曲の011。一面の草原を風が渡る。D ドリア・60。笛と竪琴の強さが、8小節周期の風のうねりに合わせてゆれる。山なし。",
       harm_scenes=["草原1", "草原2", "草原3"], tail_scene="風に還る")
