# ================= ドラム（電子のドラム） =================
for b in range(S.nb):
    n, i, L, k = S.scene_of(b)
    last = i == L - 1
    if n in ("ページの音", "ページをめくる音だけ"):
        D.set(b, "." * 16, "." * 16, "." * 16)
        if n == "ページをめくる音だけ" and last: D.set(b, "." * 16, "........oooxxxXX", "." * 16)
    elif n in ("文字が飛び出す", "寄り道"):
        if i < 4 and n == "文字が飛び出す": D.set(b, "X.......X.......", "." * 16, "..x...x...x...x.")
        else: vgroove(D, b, "twostep" if n == "文字が飛び出す" else "four16", ghosts=0.3, seed=b)
        if i == 4: crash(D, b)
        if last: put_fill(D, b, "snare16")
    elif n in ("本の中", "2冊目"):
        vgroove(D, b, "twostep" if i < 8 else "four16", ghosts=0.35, seed=b)
        if i == 0: crash(D, b)
        if i == 7: put_fill(D, b, "small")
        if last: put_fill(D, b, "snare16")
    elif n == "文字が並ぶ":
        vgroove(D, b, "half" if i < 4 else "four", ghosts=0.3, seed=b)
        if i == 4: crash(D, b, "G2")
        if i == 6: put_fill(D, b, "build")
        if last: halt(D, b, 2); D.cym(b, "C2:2")          # 止め
    elif n == "曲がり角":
        if i < 6:
            vgroove(D, b, "half" if i < 4 else "four", ghosts=0.3, seed=b)
            if i == 4: crash(D, b, "G2")
        elif i == 6:                                   # 7/8 ×2（2+2+3 のアクセント）
            D.set(b, "X...X...X.....X.", "........X.......", "..x.x.x.X.x.x...")
            D.cym(b, "C2:2 R:1.5 G2:0.5")
        else:
            D.set(b, "..X...X.....X...", "......X.....XXXX", "x.X.............")
            D.tom(b, "R:1.5 C4:0.5 A3:0.5 R:1")
    elif n.startswith("迷路"):
        vgroove(D, b, "four16" if n != "迷路を走る2" else "jersey", ghosts=0.3, seed=b)   # 2回目はジャージークラブに
        if i % 8 == 0: crash(D, b, "C2" if i % 16 == 0 else "G2")
        if i % 8 == 7 and not last: put_fill(D, b, "snare16" if i % 16 == 7 else "tomdown")
        if last and n == "迷路を走る": put_fill(D, b, "tomdown")
        if last and n == "迷路を走る2": halt(D, b, 1); D.cym(b, "C2:4")
        if last and n == "迷路の出口": put_fill(D, b, "snare16")
    elif n == "行き止まり":
        vgroove(D, b, "half", ghosts=0.45, seed=b, h="x...x...x...x...")
        if not last: D.cym(b, ("C2:1 " if i == 0 else "D2:1 ") + "D2:1 D2:1 D2:1"); D.H[b] = "." * 16
        if last: put_fill(D, b, "lift")
    elif n == "マリンバのソロ":
        vgroove(D, b, "twostep", ghosts=0.4, seed=b)
        if i == 0: crash(D, b)
        if i % 4 == 3: put_fill(D, b, "small" if i < 7 else "tomtrip")
    elif n == "出口の光":
        D.set(b, "X...X...X...X...", "." * 16, "." * 16 if i < 4 else "..x...x...x...x.")
        if i == 6: put_fill(D, b, "build")
        if last: D.set(b, "X...X...X.......", "xxxxXXXXXXXX....", "." * 16)
    elif n == "本を閉じる":
        if i < 4: vgroove(D, b, "twostep", ghosts=0.3, seed=b)
        if i == 0: crash(D, b)
        if i == 3: put_fill(D, b, "tomdown")
        if i == 4: D.set(b, "X" + "." * 15, "X" + "." * 15, "." * 16); D.cym(b, "C2:8")
        if i == 5: D.set(b, "." * 16, "." * 16, "." * 16)

