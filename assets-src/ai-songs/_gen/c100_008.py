# ケルト・フルート100曲「銀の笛と百の夜」008 港の別れ Parting at the Pier（2026-10-28）。表は docs/sound/celtic-flute-100-plan.md
# 物語（オーボエは無しにした。笛が主役。2026-10-28 人間の指示）: 港で、旅立つ人を見送る。岸の人々のざわめき→手を振る→舟が遠ざかる→水平線（終盤にやわらかい山）→最後は一人の笛だけが残る。
# 型: 下がって上がる別れの旋律。001と同じく、一つ一つの音を4分音符で弾いてなめらかにつなぎ、フレーズの終わりだけ長くのばす。
# 強さ: ざわめき(pp)→手を振る(p)→遠ざかる(p)→水平線(mp, 山)→一人の笛(pp)
import sys
from c100_common import *

S = Song("C100", "008-parting-at-the-pier", "港の別れ", "Parting at the Pier", 58, 4, "A", "minor", "ケルト（幻想）")
S.kit = "naked"; S.keep_old_synth = True
S.scene("ざわめき", 4, "intro", ["Am", "F", "C", "Am"])
S.scene("手を振る", 16, "verse", ["Am", "F", "C", "G", "Am", "Dm", "Em", "Am", "F", "C", "Dm", "Em", "F", "G", "Am", "Am"])
S.scene("遠ざかる", 16, "verse", ["Dm", "Am", "F", "C", "Dm", "Am", "Em", "Am", "F", "G", "Em", "Am", "Dm", "G", "C", "Em"])
S.scene("水平線", 16, "chorus", ["F", "C", "Dm", "Am", "F", "C", "G", "Am", "Dm", "F", "C", "G", "F", "G", "Am", "Am"])
S.scene("一人の笛", 8, "outro", ["Am", "F", "Am", "Am", "Am", "Am", "Am", "Am"])
NAMES = ["ざわめき", "手を振る", "遠ざかる", "水平線", "一人の笛"]

c = make(S, NAMES,
         [("ざわめき", 0, 0.66), ("手を振る", 0, 0.6), ("手を振る", 15, 0.66), ("遠ざかる", 0, 0.6), ("遠ざかる", 15, 0.62),
          ("水平線", 0, 0.68), ("水平線", 10, 0.88), ("水平線", 15, 0.62), ("一人の笛", 0, 0.5), ("一人の笛", 7, 0.3)],
         {"手を振る": 0.62, "遠ざかる": 0.6, "水平線": 0.66, "一人の笛": 0.5},
         flute_gain={"手を振る": 1.3, "遠ざかる": 1.3, "水平線": 1.2, "一人の笛": 1.2}, intro="ざわめき", passing=True)
# ---------- 旋律（A エオリア。下がって上がる別れの旋律） ----------
put_melody(c, "手を振る", [
    ["R:1 5:1 4:1 3:1", "1:1 2:1 3:2", "5:1 4:1 3:1 2:1", "7,:3 R:1"],
    ["1:1 7,:1 1:1 3:1", "4:3 R:1", "3:1 2:1 7,:1 2:1", "1:3 R:1"],
    ["3:1 4:1 5:1 6:1", "5:3 R:1", "4:1 3:1 2:1 4:1", "2:3 R:1"],
    ["1:1 2:1 3:1 5:1", "5:2 4:1 2:1", "3:1 2:1 7,:1 2:1", "1:3 R:1"]], 4)
put_melody(c, "遠ざかる", [
    ["4:1 3:1 2:1 1:1", "3:3 R:1", "6,:1 7,:1 1:1 3:1", "5:3 R:1"],
    ["4:1 5:1 6:1 4:1", "3:3 R:1", "2:1 3:1 2:1 7,:1", "1:3 R:1"],
    ["6:1 5:1 4:1 3:1", "2:1 4:1 5:2", "5:1 4:1 3:1 2:1", "1:3 R:1"],
    ["4:1 3:1 2:1 4:1", "5:1 4:1 2:2", "3:1 2:1 1:1 3:1", "2:3 R:1"]], 4)
put_melody(c, "水平線", [
    ["1:1 3:1 5:1 6:1", "5:3 R:1", "4:1 5:1 6:1 5:1", "3:3 R:1"],
    ["6:1 7:1 1':1 6:1", "5:3 R:1", "4:1 5:1 7:1 5:1", "1':3 R:1"],
    ["1':1 7:0.5 6:0.5 4:1 6:1", "1':2 7:1 6:1", "5:1 4:1 3:1 5:1", "7:3 R:1"],
    ["6:1 5:1 4:1 3:1", "2:1 4:1 5:1 7,:1", "1:1 2:1 3:1 2:1", "1:4"]], 4)
put_bars(c, "一人の笛", ["5:1 4:1 3:2", "R:4", "3:1 2:1 1:2", "R:4", "1:4", "R:4", "R:4", "R:4"], 4)

# ---------- 伴奏 ----------
for b in range(c.NB):
    n, i, L, k = S.scene_of(b); ch = S.chords[b]
    lo = low(ch, "C2"); t = tones(ch, "D3", "D6")
    if n == "ざわめき":
        v = voice(ch, 57, 3, spread=True)
        for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
        c.HARP.bar(b, f"{nm(t[0])}:1 {nm(t[1])}:1 {nm(t[2])}:1 {nm(t[3])}:1")
    elif n in ("手を振る", "遠ざかる", "水平線"):
        c.HARP.bar(b, f"{nm(t[0])}:1 {nm(t[1])}:1 {nm(t[2])}:1 {nm(t[1])}:1" if i % 2 == 0 else f"{nm(t[1])}:2 {nm(t[2])}:2")
        if i % 4 == 3: c.HARP2.bar(b, f"R:2 {nm(t[-2])}:2")
        c.LOW.bar(b, f"{nm(lo + 12 if lo < 40 else lo)}:4")
        v = voice(ch, 57, 3, spread=True)
        if n != "手を振る" or i >= 4:
            for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
    elif n == "一人の笛":
        if i < 2:
            v = voice(ch, 57, 3, spread=True)
            for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
        if i in (1, 3): c.HARP.bar(b, f"{nm(t[1])}:4")

finish(c, "--sound celtic-fantasy --orchestra vsco --piano salamander --space dome --space-wet 0.3 --master -15 --widen 1.0",
       "ケルト・フルート100曲の008。港で旅立つ人を見送る。A エオリア・58。舟が遠ざかり、最後は一人の笛。",
       harm_scenes=["手を振る", "遠ざかる", "水平線"], tail_scene="一人の笛")
