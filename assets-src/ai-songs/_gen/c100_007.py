# ケルト・フルート100曲「銀の笛と百の夜」007 潮の呼び声 Call of the Tide（2026-10-28）。表は docs/sound/celtic-flute-100-plan.md
# 物語: 引き潮の砂浜。潮が引いて遠ざかり（旋律が下がる）、やがて満ちて戻ってくる（旋律が上がる）。波のように2回、小さな山。
#       旋律の上下と波の満ち引きを同じ周期（8小節）にそろえる。ナイロンギターが波の足あとのように分散和音でゆれる。始め：波の音／終わり：波の音。
# 強さ: 波(pp)→引く(p)→満ちる1(mp, 山1)→引く2(p)→満ちる2(mp, 山2・少し高い)→波に戻る(pp)
import sys
from c100_common import *

S = Song("C100", "007-call-of-the-tide", "潮の呼び声", "Call of the Tide", 64, 4, "D", "dorian", "ケルト（幻想）")
S.kit = "naked"; S.keep_old_synth = True
S.scene("波", 4, "intro", ["Dm7", "Dm7", "G", "Dm7"])
S.scene("引く1", 16, "verse", ["Dm7", "G", "Am7", "Dm7", "C", "G", "Am7", "Dm7", "Dm7", "G", "F", "C", "Am7", "G", "Dm7", "Dm7"])
S.scene("満ちる1", 16, "chorus", ["F", "C", "G", "Dm7", "F", "C", "Am7", "G", "Dm7", "G", "F", "C", "G", "Am7", "Dm7", "Dm7"])
S.scene("引く2", 16, "verse", ["Dm7", "Am7", "G", "Dm7", "C", "G", "F", "Dm7", "Am7", "G", "Dm7", "C", "F", "G", "Am7", "Dm7"])
S.scene("満ちる2", 16, "chorus", ["F", "C", "G", "Dm7", "F", "G", "Am7", "C", "Dm7", "G", "F", "C", "G", "Am7", "Dm7", "Dm7"])
S.scene("波に戻る", 8, "outro", ["Dm7", "G", "Dm7", "Dm7", "Dm7", "Dm7", "Dm7", "Dm7"])
NAMES = ["波", "引く1", "満ちる1", "引く2", "満ちる2", "波に戻る"]

c = make(S, NAMES,
         [("波", 0, 0.6), ("引く1", 0, 0.58), ("引く1", 12, 0.5), ("満ちる1", 0, 0.62), ("満ちる1", 10, 0.82), ("満ちる1", 15, 0.6),
          ("引く2", 0, 0.56), ("引く2", 12, 0.5), ("満ちる2", 0, 0.64), ("満ちる2", 10, 0.9), ("満ちる2", 15, 0.6),
          ("波に戻る", 0, 0.5), ("波に戻る", 7, 0.3)],
         {"引く1": 0.65, "満ちる1": 0.7, "引く2": 0.65, "満ちる2": 0.7, "波に戻る": 0.8},
         flute_gain={"引く1": 1.3, "満ちる1": 1.2, "引く2": 1.3, "満ちる2": 1.2, "波に戻る": 1.1}, intro="波", passing=True, tension=True)
GTR = S.track("ナイロンギター", "guitar", patch="nylonGuitar", volume=0.07, pan=0.25, reverb=0.4, barGain=c.g())

# ---------- 旋律（D ドリア。8小節で1回の波：下がる→上がる。001と同じく、一つ一つの音を4分音符で弾いてなめらかにつなぐ） ----------
put_melody(c, "引く1", [
    ["R:1 5:1 6:1 5:1", "4:1 3:1 2:1 3:1", "4:3 R:1", "3:1 2:1 1:1 2:1"],
    ["1:3 R:1", "7,:1 1:1 2:1 1:1", "7,:1 6,:1 5,:1 6,:1", "5,:3 R:1"],
    ["5,:1 6,:1 7,:1 1:1", "2:1 3:1 4:1 3:1", "2:1 3:1 5:1 4:1", "3:3 R:1"],
    ["4:1 5:1 6:1 5:1", "4:1 3:1 2:1 3:1", "2:1 1:1 7,:1 2:1", "1:3 R:1"]], 5)
put_melody(c, "満ちる1", [
    ["5,:1 1:1 2:1 3:1", "4:1 5:1 6:1 5:1", "6:3 R:1", "5:1 4:1 3:1 4:1"],
    ["5:1 6:1 7:1 6:1", "5:3 R:1", "4:1 3:1 2:1 3:1", "4:3 R:1"],
    ["3:1 4:1 5:1 6:1", "7:2 6:1 5:1", "6:1 7:1 6:1 4:1", "5:3 R:1"],
    ["4:1 3:1 2:1 3:1", "4:1 3:1 2:1 7,:1", "1:1 2:1 7,:1 6,:1", "1:3 R:1"]], 5)
put_melody(c, "引く2", [
    ["R:1 6:1 5:1 4:1", "3:1 4:1 3:1 2:1", "1:3 R:1", "2:1 1:1 7,:1 1:1"],
    ["7,:1 6,:1 5,:1 6,:1", "7,:3 R:1", "1:1 7,:1 6,:1 7,:1", "5,:3 R:1"],
    ["6,:1 7,:1 1:1 2:1", "3:1 2:1 1:1 2:1", "3:1 4:1 5:1 3:1", "2:3 R:1"],
    ["3:1 2:1 1:1 7,:1", "6,:1 7,:1 1:1 2:1", "7,:1 6,:1 5,:1 7,:1", "1:3 R:1"]], 5)
put_melody(c, "満ちる2", [
    ["5,:1 2:1 3:1 4:1", "5:1 6:1 7:1 6:1", "7:3 R:1", "6:1 5:1 4:1 5:1"],
    ["6:1 7:1 6:1 5:1", "4:3 R:1", "5:1 6:1 7:1 5:1", "6:3 R:1"],
    ["5:1 6:1 7:1 6:1", "7:2 6:1 5:1", "4:1 5:1 6:1 4:1", "5:3 R:1"],
    ["6:1 5:1 4:1 3:1", "2:1 3:1 4:1 2:1", "3:1 2:1 7,:1 2:1", "1:4"]], 5)
put_bars(c, "波に戻る", ["3:1 2:1 1:2", "R:4", "5,:1 6,:1 1:2", "R:4", "1:4", "R:4", "R:4", "R:4"], 5)

# ---------- 伴奏 ----------
for b in range(c.NB):
    n, i, L, k = S.scene_of(b); ch = S.chords[b]
    lo = low(ch, "C2"); t = tones(ch, "D3", "D6")
    if n == "波":
        v = voice(ch, 58, 3, spread=True)
        for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
        if i >= 2: GTR.bar(b, f"{nm(t[0])}:1 {nm(t[1])}:1 {nm(t[2])}:1 {nm(t[1])}:1")
    elif n in ("引く1", "満ちる1", "引く2", "満ちる2"):
        # ナイロンギター：波のように、引くときは疎に・満ちるときは密に
        if n.startswith("引く"):
            GTR.bar(b, f"{nm(t[0])}:1 {nm(t[1])}:1 {nm(t[2])}:1 {nm(t[1])}:1" if i % 2 == 0 else f"{nm(t[1])}:2 {nm(t[2])}:2")
        else:
            GTR.bar(b, f"{nm(t[0])}:0.5 {nm(t[1])}:0.5 {nm(t[2])}:0.5 {nm(t[3])}:0.5 {nm(t[2])}:0.5 {nm(t[1])}:0.5 {nm(t[2])}:0.5 {nm(t[1])}:0.5")
        c.HARP.bar(b, f"{nm(t[0])}:4" if i % 2 == 0 else f"R:2 {nm(t[2])}:2")
        if i % 4 == 3: c.HARP2.bar(b, f"R:2 {nm(t[-2])}:2")
        c.LOW.bar(b, f"{nm(lo + 12 if lo < 40 else lo)}:4")
        v = voice(ch, 58, 3, spread=True)
        if n.startswith("満ちる") or i >= 4:
            for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
    elif n == "波に戻る":
        if i < 6:
            v = voice(ch, 58, 3, spread=True)
            for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
        if i in (0, 2): GTR.bar(b, f"{nm(t[0])}:1 {nm(t[1])}:1 {nm(t[2])}:2")
        if i in (1, 3): c.HARP.bar(b, f"{nm(t[1])}:4")

rich(c, choir_scenes=["満ちる1", "満ちる2"], pulse_scenes=["引く1", "満ちる1", "引く2", "満ちる2"], guitar=False)

finish(c, "--sound celtic-fantasy --orchestra vsco --piano salamander --space dome --space-wet 0.3 --master -15 --widen 1.0",
       "ケルト・フルート100曲の007。引き潮の砂浜。D ドリア・64。笛とナイロンギター。旋律の上下と波の満ち引きが同じ8小節の周期で、2回の小さな山。",
       harm_scenes=["引く1", "満ちる1", "引く2", "満ちる2"], tail_scene="波に戻る")
