def bars():
    """120小節ぶんの、小節ごとのトークン文字列（歌なしは R:4）。"""
    out = []
    for key in ORDER:
        out += ["R:4"] * 8 if key is None else V[key]
    return out

def notes():
    """(開始拍, 長さ拍, 音名, かな) のリスト。小節の長さが4拍でなければ止める。"""
    res = []; t = 0.0
    for i, bar in enumerate(bars()):
        s = 0.0
        for tok in bar.split():
            if tok.startswith("R:"):
                d = float(tok[2:])
            else:
                kana, pitch, d = tok.split(":"); d = float(d)
                res.append((t + s, d, pitch, kana))
            s += d
        assert abs(s - 4) < 1e-9, (i + 1, s, bar)
        t += 4
    return res

if __name__ == "__main__":
    ns = notes()
    print(len(bars()), "bars", len(ns), "notes", "lyric:", "".join(n[3] for n in ns)[:60])
