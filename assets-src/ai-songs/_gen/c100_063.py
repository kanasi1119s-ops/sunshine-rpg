# ケルト・フルート100曲「銀の笛と百の夜」063 麦酒の泡 Ale Foam — 第3版（2026-11-01。docs/sound/celtic-study/E-100-plan.md）
# 物語: 村の酒場の夜。ピアノ弾きがはずむ伴奏を弾き、隣の席の男がスプーンを打ち鳴らす。エイラも笛で加わり、
#   はじめはゆったりしたホーンパイプ。夜がふけて盛りあがると、同じ節がリールの速さになって転がりだす。
# 調べ: 喜び。形: ホーンパイプ（AABB×2）→ 同じ節のリール（AABB → BB）。最後は「タン・タン・タン」。
# 拍子・速さ: 4/4・♩=84 → 112。旋法: A ミクソリディア（G♮）。
# 主役は笛（陽気な笛）。伴奏の主役: ピアノのヴァンプ（左手は1・3拍目のオクターブ、右手は2・4拍目の和音）。打楽器はスプーン（カホンの縁の高い音で）。
#   竪琴・ギター・パッド・弦・2本目の笛は使わない。
# この曲だけ: ホーンパイプの付点のはずみが、リールになると丸く（まっすぐな8分に）なる。同じ節で。
# 始まり: いきなり全員 → 終わり: タン・タン・タン（全員で4分音符3つ）。
# 山: 2つ（ホーンパイプの2周目と、リールの終わり）。
import sys, json, re
from c100_common import *
from c100_v2 import *

S = Song("C100", "063-ale-foam", "麦酒の泡", "Ale Foam", 112, 4, "A", "mixolydian", "ケルト（幻想）")
S.kit = "naked"; S.keep_old_synth = True
S.extra.update({"human": 0.35})
K = Key("A", "mixolydian", 4)
CA = ["A", "D", "A", "E", "A", "D", "E", "A"]; CB = ["A", "D", "A", "G", "A", "D", "E", "A"]
T = CA * 2 + CB * 2
SC = [("ホーンパイプ", 32, "verse", T), ("ホーンパイプ2", 32, "chorus", T), ("移る", 2, "verse", ["E", "E"]), ("リール", 32, "verse", T),
      ("リール2", 16, "chorus", CB * 2), ("タン・タン・タン", 1, "outro", ["A"])]
for n, L, kd, ch in SC: S.scene(n, L, kd, ch)
NAMES = [x[0] for x in SC]
c = make(S, NAMES,
         [("ホーンパイプ", 0, 0.8), ("ホーンパイプ2", 0, 0.84), ("ホーンパイプ2", 31, 0.92), ("移る", 0, 0.8), ("リール", 0, 0.82), ("リール2", 0, 0.88),
          ("リール2", 15, 0.96), ("タン・タン・タン", 0, 0.96)],
         {}, flute_gain={n: 1.15 for n in NAMES}, intro="ホーンパイプ", passing=True, tension=False)
S.fix_avoid = lambda t: 0
s = c.s0
S.tempo = [{"bar": 1, "bpm": 84}, {"bar": s["移る"] + 1, "bpm": 112, "ramp": 2}]
B = S.beats
G = c.g()
# ピアノ: 1音は ×1.4 で笛とほぼ同じ、右手の和音（3音）は 0.08 前後（016）
LH = [S.track(f"ピアノ（左手のオクターブ{j + 1}）", "piano", volume=0.2, pan=-0.2, reverb=0.3, sustain=0.6, barGain=G) for j in range(2)]
RH = [S.track(f"ピアノ（右手の和音{j + 1}）", "piano", volume=0.07, pan=0.05 + 0.05 * j, reverb=0.3, sustain=0.4, barGain=G) for j in range(3)]
# 試し書き出し: カホンの縁（G3・F3・0.22）は笛より約28dB 小さい → gainDb 18
SP = [S.track(f"スプーン{j + 1}", "cajon", volume=0.22, gainDb=18, pan=0.3 - 0.1 * j, reverb=0.2, barGain=G) for j in range(2)]

# ---------- 節（8分＝0.5。1=A4。B5 より上には行かない） ----------
A = ["1:0.5 3:0.5 5:0.5 3:0.5 1':0.5 5:0.5 3:0.5 5:0.5", "4:0.5 6:0.5 1':0.5 6:0.5 5:0.5 4:0.5 3:0.5 2:0.5",
     "1:0.5 3:0.5 5:0.5 1':0.5 7:0.5 5:0.5 4:0.5 3:0.5", "2:0.5 3:0.5 4:0.5 2:0.5 7,:0.5 5,:0.5 7,:0.5 2:0.5",
     "1:0.5 3:0.5 5:0.5 3:0.5 1':0.5 5:0.5 3:0.5 5:0.5", "4:0.5 6:0.5 1':0.5 6:0.5 5:0.5 4:0.5 3:0.5 2:0.5",
     "3:0.5 5:0.5 1':0.5 5:0.5 4:0.5 2:0.5 7,:0.5 2:0.5", "1:0.5 R:0.5 1:0.5 R:0.5 1:1 R:1"]
Bm = ["5:0.5 1':0.5 2':0.5 1':0.5 7:0.5 1':0.5 6:0.5 5:0.5", "4:0.5 5:0.5 6:0.5 1':0.5 2':0.5 1':0.5 6:0.5 4:0.5",
      "5:0.5 1':0.5 2':0.5 1':0.5 7:0.5 5:0.5 3:0.5 5:0.5", "7:0.5 2':0.5 1':0.5 7:0.5 6:0.5 5:0.5 4:0.5 2:0.5",
      "5:0.5 1':0.5 2':0.5 1':0.5 7:0.5 1':0.5 6:0.5 5:0.5", "6:0.5 4:0.5 1':0.5 6:0.5 5:0.5 3:0.5 1':0.5 5:0.5",
      "3:0.5 5:0.5 1':0.5 5:0.5 4:0.5 2:0.5 7,:0.5 2:0.5", "1:0.5 R:0.5 1:0.5 R:0.5 1:1 R:1"]
TUNE = A + A + Bm + Bm
play_melody(c, "ホーンパイプ", TUNE, 4, "hornpipe", key=K, density=0.35, seed=6301)       # 付点のはずみ
play_melody(c, "ホーンパイプ2", TUNE, 4, "hornpipe", key=K, density=0.5, seed=6302)
play_melody(c, "移る", ["5:1 4:1 3:1 2:1", "7,:1 5,:1 6,:0.5 7,:0.5 R:1"], 4, "reel", key=K, density=0.0)
play_melody(c, "リール", TUNE, 4, "reel", key=K, density=0.45, seed=6303)                # まっすぐな8分（丸くなる）
play_melody(c, "リール2", Bm + Bm, 4, "reel", key=K, density=0.55, seed=6304)
s0 = s["タン・タン・タン"]
c.FLUTE.bar(s0, "A5:0.6! R:0.4 A5:0.6! R:0.4 A4:0.8! R:1.2")

# ---------- ピアノのヴァンプとスプーン ----------
def tri(ch):
    m = re.match(r"^([A-G][#b]?)(m?)", ch); r = PC[m.group(1)]
    return r, (r + (3 if m.group(2) else 4)) % 12, (r + 7) % 12
def near(pc, lo):
    return lo + (pc - lo) % 12
for b in range(s["タン・タン・タン"]):
    n, i, Lb, k = S.scene_of(b); ch = S.chords[b]; r, th, fi = tri(ch)
    lo = near(r, 33); f5 = lo + 7
    up = [near(r, 57), near(th, 57), near(fi, 57)]
    hp = n.startswith("ホーンパイプ")
    LH[0].bar(b, f"{nm(lo)}:0.5! R:1.5 {nm(f5 if i % 2 else lo)}:0.5 R:1.5"); LH[1].bar(b, f"{nm(lo + 12)}:0.5 R:1.5 {nm((f5 if i % 2 else lo) + 12)}:0.5, R:1.5")
    for j, m in enumerate(up):
        if hp:
            RH[j].bar(b, f"R:1 {nm(m)}:0.4, R:0.6 R:1 {nm(m)}:0.4, R:0.6")
        else:                                                  # リール：右手は裏拍で弾む
            RH[j].bar(b, f"R:1 {nm(m)}:0.3, R:0.2 {nm(m)}:0.3, R:0.2 R:1 {nm(m)}:0.3, R:0.2 {nm(m)}:0.3, R:0.2")
    # スプーン（カホンの縁の高い音 F3・G3）：ホーンパイプは「タッ・カ」、リールは8分で転がる
    sp = SP[b % 2]
    if hp:
        sp.bar(b, " ".join(["G3:0.75! F3:0.25,", "G3:0.75 F3:0.25,", "G3:0.75! F3:0.25,", "G3:0.75 F3:0.25,"] if i % 8 != 7 else ["G3:0.75! F3:0.25,", "G3:0.5! G3:0.5!", "G3:1!", "R:1"]))
    else:
        sp.bar(b, " ".join(["G3:0.5! F3:0.5,", "G3:0.5 F3:0.5,", "G3:0.5! F3:0.5,", "G3:0.5 F3:0.5,"] if i % 8 != 7 else ["G3:0.5! F3:0.5,", "G3:0.5! G3:0.5!", "G3:1!", "R:1"]))
s0 = s["タン・タン・タン"]
LH[0].bar(s0, "A1:0.6! R:0.4 A1:0.6! R:0.4 A1:0.8! R:1.2"); LH[1].bar(s0, "A2:0.6! R:0.4 A2:0.6! R:0.4 A2:0.8! R:1.2")
for j, m in enumerate((57, 61, 64)): RH[j].bar(s0, f"{nm(m)}:0.6! R:0.4 {nm(m)}:0.6! R:0.4 {nm(m)}:0.8! R:1.2")
SP[0].bar(s0, "G3:0.6! R:0.4 G3:0.6! R:0.4 G3:0.8! R:1.2")

finish(c, "--sound celtic-fantasy --orchestra vsco --piano salamander --space vale --space-wet 0.16 --master -15 --widen 1.1 --side-hpf 200",
       "ケルト・フルート100曲の063（第3版）。村の酒場の夜。A ミクソリディア。いきなり全員で、ピアノのヴァンプ（左手は1・3拍目のオクターブ、右手は2・4拍目の和音）とスプーンに乗って、笛がホーンパイプ（♩=84、付点のはずみ）を AABB で2周。盛りあがると2小節で ♩=112 に上がり、同じ節がリールのまっすぐな8分で転がりだす。山は2つ。最後は全員の「タン・タン・タン」。",
       harm_scenes=None, tail_scene="タン・タン・タン", double=False, fill=False, pads=False)
air = {"pre": 0.2, "tail": 3.0, "layers": [{"file": "0595", "db": -46, "hp": 200, "lp": 4000, "wide": 0.012, "duck": 0.4, "fade": 6}],
       "fx": {"far": {"db": -30, "delay": 0.15, "lp": 3000, "rt": 1.6}}}
json.dump(air, open("/tmp/cel/w/air063.json", "w"), ensure_ascii=False)
