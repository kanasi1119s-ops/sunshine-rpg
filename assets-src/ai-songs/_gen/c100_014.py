# ケルト・フルート100曲「銀の笛と百の夜」014 迷い羊 The Lost Lamb（2026-10-28）。表は docs/sound/celtic-flute-100-plan.md
# 物語: 霧の丘で、はぐれた子羊を探す。笛が上へ呼びかけ、耳をすます。呼ぶたびに、遠くの鳴き声（本物の録音）が少しずつ近づいてくる。
#       見つけた所で小さな山。最後は安心した長い音。
# 型: 呼びかけ（上がる音型）と、耳をすます間（笛は休むが、伴奏はやわらかく続けて音が急に小さくならないようにする）のくり返し。
#     表ではオーボエもいたが、笛を主役にする方針（2026-10-28）で笛だけにした。重ね方は「音の重ね方の勉強ノート」どおり。
import sys, json
from c100_common import *

BPM = 62
S = Song("C100", "014-the-lost-lamb", "迷い羊", "The Lost Lamb", BPM, 4, "A", "dorian", "ケルト（幻想）")
S.kit = "naked"; S.keep_old_synth = True
S.scene("霧", 4, "intro", ["Am", "Am", "D", "Am"])
S.scene("呼ぶ1", 16, "verse", ["Am", "D", "Am", "Am", "G", "D", "Am", "Am", "C", "G", "D", "Am", "Em", "D", "Am", "Am"])
S.scene("呼ぶ2", 16, "verse", ["Am", "D", "Am", "Am", "G", "D", "Am", "Am", "C", "G", "D", "Am", "Em", "D", "Am", "Am"])
S.scene("呼ぶ3", 8, "verse", ["C", "G", "D", "Am", "Em", "D", "Am", "Am"])
S.scene("見つけた", 12, "chorus", ["C", "D", "G", "Em", "C", "D", "Em", "Am", "C", "D", "G", "Am"])
S.scene("安堵", 12, "outro", ["Am", "D", "Am", "C", "G", "D", "Am", "Am", "Am", "Am", "Am", "Am"])
NAMES = ["霧", "呼ぶ1", "呼ぶ2", "呼ぶ3", "見つけた", "安堵"]

c = make(S, NAMES,
         [("霧", 0, 0.6), ("呼ぶ1", 0, 0.6), ("呼ぶ2", 0, 0.64), ("呼ぶ3", 0, 0.68), ("見つけた", 0, 0.76), ("見つけた", 5, 0.88),
          ("見つけた", 11, 0.7), ("安堵", 0, 0.62), ("安堵", 11, 0.3)],
         {"呼ぶ1": 0.62, "呼ぶ2": 0.64, "呼ぶ3": 0.66, "見つけた": 0.68, "安堵": 0.6},
         flute_gain={"呼ぶ1": 1.3, "呼ぶ2": 1.25, "呼ぶ3": 1.25, "見つけた": 1.2, "安堵": 1.2}, intro="霧", passing=True, tension=True)

PIZ = S.track("ピチカート（足どり）", "strings", patch="pizzicato", volume=0.09, pan=-0.2, reverb=0.4, barGain=c.g())

# ---------- 笛（A ドリア。上がる呼びかけ→耳をすます） ----------
CALL1 = [["R:1 1:1 3:1 5:1", "6:3 R:1", "R:4", "R:4"],
         ["5:1 7:1 2':1 7:1", "4:1 6:1 1':1 6:1", "R:4", "R:4"],
         ["3:1 5:1 7:1 5:1", "7:1 2':1 7:1 5:1", "4:1 6:1 1':1 2':1", "1':3 R:1"],
         ["5:1 7:1 2':1 7:1", "6:1 4:1 2:1 4:1", "R:4", "R:4"]]
CALL2 = [["R:1 3:1 5:1 1':1", "1':3 R:1", "R:4", "R:4"],
         ["7:1 2':1 3':1 2':1", "1':1 2':1 1':1 6:1", "R:4", "R:4"],
         ["3:1 5:1 1':1 3':1", "2':1 7:1 5:1 7:1", "6:1 1':1 2':1 1':1", "1':3 R:1"],
         ["2':1 1':1 7:1 5:1", "6:1 4:1 6:1 1':1", "R:4", "R:4"]]
put_melody(c, "呼ぶ1", CALL1, 4)
put_melody(c, "呼ぶ2", CALL2, 4)
put_melody(c, "呼ぶ3", [["3:1 5:1 1':1 3':1", "2':3 R:1", "R:4", "1':1 3':1 2':1 1':1"],
                        ["2':1 1':1 7:1 5:1", "6:3 R:1", "R:4", "R:4"]], 4)
put_melody(c, "見つけた", [
    ["1':1 2':1 3':1 2':1", "1':1 2':1 1':1 6:1", "7:1 2':1 7:1 5:1", "5:3 R:1"],
    ["3:1 5:1 1':1 3':1", "1':1 6:1 4:1 6:1", "5:1 7:1 2':1 7:1", "1':3 R:1"],
    ["3':1 2':1 1':1 5:1", "6:1 1':1 2':1 1':1", "7:1 5:1 2:1 5:1", "1':3 R:1"]], 4)
put_bars(c, "安堵", ["5:1 3:1 1:2", "6:3 R:1", "5:1 3:1 1:2", "3:4", "2:1 4:1 7:2", "6:4", "1:4", "R:4", "1':4", "R:4", "R:4", "R:4"], 4)

# ---------- 伴奏（笛が休む間も、やわらかく続ける） ----------
for b in range(c.NB):
    n, i, L, k = S.scene_of(b); ch = S.chords[b]
    lo = low(ch, "C2"); t = tones(ch, "D3", "D6")
    if n == "霧":   # 始まり：ピチカートだけが、手さぐりの足どりのように（歩いては止まる）
        z = tones(ch, "A3", "A4")
        PIZ.bar(b, f"{nm(z[0])}:1 {nm(z[1])}:1 R:2" if i % 2 == 0 else f"{nm(z[2])}:1 R:1 {nm(z[1])}:1 R:1")
        continue
    v = voice(ch, 57, 3, spread=True)
    for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
    if n == "霧":
        if i >= 2: c.HARP.bar(b, f"{nm(t[0])}:2 {nm(t[2])}:2")
    elif n in ("呼ぶ1", "呼ぶ2", "呼ぶ3", "見つけた"):
        c.HARP.bar(b, f"{nm(t[0])}:1 {nm(t[2])}:1 {nm(t[4 % len(t)])}:1 {nm(t[2])}:1" if n == "見つけた" else f"{nm(t[0])}:2 {nm(t[2])}:2")
        if i % 4 == 3: c.HARP2.bar(b, f"R:2 {nm(t[-2])}:2")
        c.LOW.bar(b, f"{nm(lo + 12 if lo < 40 else lo)}:4")
    elif n == "安堵" and i in (0, 2, 4):
        c.HARP.bar(b, " ".join(f"{nm(t[q % len(t)])}:1" for q in (0, 2, 4, 6)))

rich(c, choir_scenes=["見つけた"], pulse_scenes=["呼ぶ3", "見つけた"])

finish(c, "--sound celtic-fantasy --orchestra vsco --piano salamander --space dome --space-wet 0.3 --master -15 --widen 1.0",
       "ケルト・フルート100曲の014。霧の丘ではぐれた子羊を探す。A ドリア・62。上がる呼びかけと耳をすます間のくり返し。呼ぶたびに遠くの鳴き声が近づき、見つけた所で小さな山。",
       harm_scenes=["呼ぶ1", "呼ぶ2", "呼ぶ3", "見つけた"], tail_scene="安堵")

# ---------- 空気：耳をすます間に、遠くの鳴き声（呼ぶたびに近づく＝大きく・明るく） ----------
BAR = 4 * 60 / BPM
SEEK = [4.3, 12.0, 40.4, 61.0, 20.4, 42.1]
ev = []; k = 0
for n in ("呼ぶ1", "呼ぶ2", "呼ぶ3"):
    for p in range(0, c.sc_len[n], 4):
        b = c.s0[n] + p + 2
        if b >= c.s0[n] + c.sc_len[n]: continue
        if n == "呼ぶ1" and p == 8: continue           # 3つめの呼びかけは、笛が最後まで吹く
        if n == "呼ぶ2" and p == 8: continue
        near = k / 6
        ev.append({"t": round(b * BAR + 0.5, 2), "file": "0821", "db": round(-40 + 12 * near, 1), "len": 3.0, "pan": round(0.5 - 0.4 * near, 2),
                   "seek": SEEK[k % len(SEEK)], "hp": 300, "lp": int(2500 + 4500 * near)})
        k += 1
air = {"pre": 1.5, "tail": 5.0, "layers": [
    {"file": "0908", "db": -36, "hp": 150, "lp": 5000, "lfo": [40, 0.4], "wide": 0.014, "duck": 0.35, "fade": 10}],
    "events": ev,
    "fx": {"glass": {"hz": [440.0, 880.0, 1318.5], "db": -27, "rt": 6.0, "start": 4}, "shimmer": {"db": -30, "rt": 7.0},
           "far": {"db": -27, "delay": 0.25, "lp": 2600, "rt": 4.0}}, "intro_db": 6.0}
json.dump(air, open("/tmp/cel/w/air014.json", "w"), ensure_ascii=False)
print("鳴き声を置いた回数:", len(ev))
