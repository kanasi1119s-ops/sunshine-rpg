def chk(*lists):
    """手で書いた行が、どれも1小節（4拍）ちょうどかを確かめる"""
    for L in lists:
        for x in L:
            t = sum(float(tok.split(":", 1)[1].rstrip("!,'_~^/\\")) for tok in x.split())
            assert abs(t - 4) < 1e-6, ("4拍ではない行", t, x)


