# ケルト・フルート100曲「銀の笛と百の夜」010 出航 Setting Sail（2026-10-28）。表は docs/sound/celtic-flute-100-plan.md
# 物語: 静かな朝の港。帆を上げ、風が帆に満ちて、船が動き出す。山でティンパニが小さく転がり、直後に1拍だけ全部が息を止め、
#       そこから広い海へ。最後は広い海原の余韻。
# 型: 開放的に上がっていく旋律を2回（2回目は高く）。笛は001と同じく一音ずつなめらかに。ホルンは旋律ではなく、和音を下から支える長い音だけ。
# 強さ: 静けさ(pp)→帆を上げる(p)→風が満ちる(mp)→出航(mf, 山→1拍の無音)→広い海原(mp→p)→余韻(pp)
import sys
from c100_common import *

S = Song("C100", "010-setting-sail", "出航", "Setting Sail", 68, 4, "G", "mixolydian", "ケルト（幻想）")
S.kit = "naked"; S.keep_old_synth = True
S.scene("静けさ", 4, "intro", ["G", "G", "F", "G"])
S.scene("帆を上げる", 16, "verse", ["G", "F", "C", "G", "Em", "F", "G", "G", "C", "G", "F", "C", "Am", "F", "G", "G"])
S.scene("風が満ちる", 16, "verse", ["C", "G", "F", "C", "Em", "Am", "F", "G", "C", "Dm", "F", "C", "F", "C", "Dm", "G"])
S.scene("出航", 20, "chorus", ["G", "F", "C", "G", "G", "F", "C", "G", "G", "F", "Em", "Am", "F", "C", "Dm", "G", "C", "F", "G", "G"])
S.scene("広い海原", 8, "verse", ["G", "F", "C", "G", "Em", "F", "G", "G"])
S.scene("余韻", 8, "outro", ["F", "C", "G", "G", "G", "G", "G", "G"])
NAMES = ["静けさ", "帆を上げる", "風が満ちる", "出航", "広い海原", "余韻"]

c = make(S, NAMES,
         [("静けさ", 0, 0.6), ("帆を上げる", 0, 0.6), ("帆を上げる", 15, 0.68), ("風が満ちる", 0, 0.7), ("風が満ちる", 15, 0.8),
          ("出航", 0, 0.82), ("出航", 7, 0.95), ("出航", 8, 0.86), ("出航", 19, 0.8), ("広い海原", 0, 0.7), ("広い海原", 7, 0.62),
          ("余韻", 0, 0.55), ("余韻", 7, 0.3)],
         {"帆を上げる": 0.62, "風が満ちる": 0.66, "出航": 0.7, "広い海原": 0.66, "余韻": 0.6},
         flute_gain={"帆を上げる": 1.3, "風が満ちる": 1.25, "出航": 1.15, "広い海原": 1.2, "余韻": 1.1}, intro="静けさ", passing=True, tension=True)
HORN = S.track("ホルン（支え）", "brass", patch="horn", volume=0.07, pan=-0.2, reverb=0.55, breath=False, attack=0.25, release=0.8, bright=-0.5,
               barGain=c.g())
TIMP = S.track("ティンパニ", "strings", patch="timpani", volume=0.09, pan=0, reverb=0.4, gainDb=-4, barGain=c.g())

# ---------- 旋律（G ミクソリディア。開放的に上がる旋律を2回、2回目は高く） ----------
put_melody(c, "帆を上げる", [
    ["R:1 1:1 2:1 3:1", "4:1 5:1 6:1 4:1", "5:1 6:1 5:1 3:1", "5:3 R:1"],
    ["3:1 5:1 6:1 5:1", "4:1 6:1 1':1 6:1", "5:1 4:1 3:1 2:1", "1:3 R:1"],
    ["5:1 6:1 1':1 6:1", "5:1 3:1 2:1 3:1", "4:1 6:1 5:1 4:1", "5:3 R:1"],
    ["6:1 5:1 3:1 6:1", "4:1 3:1 2:1 4:1", "5:1 4:1 3:1 2:1", "1:3 R:1"]], 4)
put_melody(c, "風が満ちる", [
    ["5:1 6:1 1':1 2':1", "3':3 R:1", "4:1 6:1 1':1 6:1", "5:3 R:1"],
    ["6:1 5:1 3:1 5:1", "6:1 1':1 3':1 1':1", "4':1 3':1 2':1 1':1", "3':3 R:1"],
    ["5:1 6:1 1':1 6:1", "4:1 6:1 2':1 6:1", "4:1 6:1 1':1 4':1", "1':3 R:1"],
    ["4':1 3':1 2':1 1':1", "6:1 5:1 3:1 5:1", "6:1 4:1 2:1 4:1", "5:3 R:1"]], 4)
put_melody(c, "出航", [
    ["R:1 1:1 2:1 3:1", "4:1 5:1 6:1 4:1", "5:1 6:1 1':1 3':1", "1':3 R:1"],
    ["3:1 5:1 1':1 3':1", "4':2 3':1 2':1", "1':1 2':1 3':1 1':1", "2':4"],
    ["R:1 3':1 2':1 1':1", "6:1 1':1 4':1 3':1", "3':1 1':1 6:1 5:1", "6:3 R:1"],
    ["4:1 6:1 1':1 4':1", "1':1 6:1 5:1 6:1", "4:1 6:1 2':1 4':1", "3':3 R:1"],
    ["1':1 6:1 5:1 3:1", "4:1 6:1 1':1 6:1", "5:1 4:1 3:1 2:1", "1:4"]], 4)
put_melody(c, "広い海原", [
    ["3:1 2:1 1:1 2:1", "4:3 R:1", "5:1 6:1 5:1 3:1", "5:3 R:1"],
    ["3:1 5:1 6:1 5:1", "4:3 R:1", "3:1 2:1 1:1 2:1", "1:3 R:1"]], 4)
put_bars(c, "余韻", ["4:1 3:1 2:2", "R:4", "3:1 2:1 1:2", "R:4", "1:4", "R:4", "R:4", "R:4"], 4)

# ---------- 伴奏 ----------
ROLL = c.s0["出航"] + 7          # 山：ティンパニが転がる小節。次の小節の1拍目は全部が息を止める
for b in range(c.NB):
    n, i, L, k = S.scene_of(b); ch = S.chords[b]
    lo = low(ch, "C2"); t = tones(ch, "D3", "D6")
    if n == "静けさ":
        v = voice(ch, 55, 3, spread=True)
        for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
        if i >= 2: c.HARP.bar(b, f"{nm(t[0])}:2 {nm(t[2])}:2")
    elif n in ("帆を上げる", "風が満ちる", "出航", "広い海原"):
        c.HARP.bar(b, f"{nm(t[0])}:2 {nm(t[2])}:2" if i % 2 == 0 else f"{nm(t[1])}:2 {nm(t[3])}:2")
        if i % 4 == 3: c.HARP2.bar(b, f"R:2 {nm(t[-2])}:2")
        c.LOW.bar(b, f"{nm(lo + 12 if lo < 40 else lo)}:4")
        v = voice(ch, 55, 3, spread=True)
        for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
        # ホルン：和音を下から支える長い音（旋律は吹かない）。風が満ちるから
        if n in ("風が満ちる", "出航", "広い海原"):
            h = tones(ch, "G3", "D4"); HORN.bar(b, f"{nm(h[0])}:4")
        if b == ROLL: TIMP.bar(b, "R:2 " + " ".join(f"{nm(lo + 12 if lo < 40 else lo)}:0.25" for _ in range(8)))
        elif n == "出航" and i % 4 == 0 and i != 8: TIMP.bar(b, f"{nm(lo + 12 if lo < 40 else lo)}:2 R:2")
    elif n == "余韻":
        v = voice(ch, 55, 3, spread=True)
        for j in range(3): c.STR[j].bar(b, f"{nm(v[j])}:4")
        if i in (0, 2, 4):
            a = tones(ch, "D3", "D6"); c.HARP.bar(b, f"{nm(a[0])}:1 {nm(a[1])}:1 {nm(a[2])}:1 {nm(a[3])}:1")

rich(c, choir_scenes=["風が満ちる", "出航"], pulse_scenes=["帆を上げる", "風が満ちる", "出航", "広い海原"])

finish(c, "--sound celtic-fantasy --orchestra vsco --piano salamander --space dome --space-wet 0.3 --master -15 --widen 1.0",
       "ケルト・フルート100曲の010。帆を上げて船が海へ出る。G ミクソリディア・68。開放的に上がる旋律を2回。山でティンパニが転がり、1拍だけ全部が息を止めて、広い海へ。",
       harm_scenes=["帆を上げる", "風が満ちる", "出航", "広い海原"], tail_scene="余韻", silences=[(ROLL + 1, 0, 1)])
