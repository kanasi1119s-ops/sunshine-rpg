# 『スパーク・フロア』（仮）の歌（重音テト用。オリジナルの歌詞と旋律）。BPM126・ト短調・4/4・120小節（約3分49秒）。
# 2026-10-16、人間の指示「これ（スパーク・フロア）にテトの歌を追加しよう」。
# 1音＝1文字（ひらがな。「しゅ」などの拗音は1音）。小さい「っ」は使わない。「を」は「お」、助詞の「は」は「わ」、「へ」は「え」と書く。
# 伸ばす音（ー）は母音で書く（スパーク → す・ぱ・あ・く）。ただしサビ頭の「さあ」は、母音を分けると「ら」に聞こえたので「さ」を1拍のばす。
# 音域: D4〜Eb5（テトが無理なく歌える高さ。インストの旋律は高すぎるので、歌用に書き直した）。サビの頂点は Eb5。
# 曲の並び: イントロ8・ビルド8（歌なし）→ Aメロ16 → Bメロ8 → サビ16 → ブレイク8（歌なし）→ Aメロ8 → Bメロ8 → サビ16 → ブリッジ8（歌なし）→ サビ16

